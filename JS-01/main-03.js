console.log("3. Объект товара");

// Объект товара с двумя свойствами
const product = {
    name: "Микрофон",
    price: 5000
};

// Добавляю свойство "Категория"
product.category = "Игровые аксессуары";

// Меняю свойство "Цена"
product.price = 3000;

// Вывод объекта
console.log("Описание товара:", product);

// Вывод свойств объекта
console.log("Название:", product.name);
console.log("Цена:", product.price);
console.log("Категория:", product.category);